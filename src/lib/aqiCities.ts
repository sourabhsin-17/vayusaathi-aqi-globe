export function findCityMeta(location: IndianLocation): MonitoredCityMeta | undefined {
  return (
    ALL_MONITORED_CITIES.find((c) => c.id === location.id) ??
    ALL_MONITORED_CITIES.find(
      (c) =>
        Math.abs(c.latitude - location.latitude) < 0.14 &&
        Math.abs(c.longitude - location.longitude) < 0.14
    )
  );
}
